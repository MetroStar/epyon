// Builds web/src/* into the committed bundle web/static/{app.js,app.css}.
//   npm run build   write the bundle
//   npm run check   fail if the committed bundle is stale (used by CI)
//
// The UI still relies on inline `onclick="fn()"` handlers, which need top-level
// functions to stay global. Until those are replaced, the JS is transformed
// without bundling so declarations keep their global scope.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");

const targets = [
  { entry: "src/main.js", out: "static/app.js", banner: "/* GENERATED by web/build.mjs from web/src/main.js - do not edit. */" },
  { entry: "src/main.css", out: "static/app.css", banner: "/* GENERATED by web/build.mjs from web/src/main.css - do not edit. */" },
];

let stale = false;
for (const t of targets) {
  const result = await build({
    entryPoints: [join(root, t.entry)],
    outfile: join(root, t.out),
    bundle: false,
    write: false,
    charset: "utf8",
    target: "es2020",
    legalComments: "inline",
    banner: { [t.out.endsWith(".js") ? "js" : "css"]: t.banner },
  });
  const text = result.outputFiles[0].text;
  if (check) {
    let current = "";
    try { current = readFileSync(join(root, t.out), "utf8"); } catch { /* missing */ }
    if (current !== text) { console.error(`${t.out} is stale; run: cd web && npm run build`); stale = true; }
  } else {
    writeFileSync(join(root, t.out), text);
    console.log(`built ${t.out} (${text.length} bytes)`);
  }
}
process.exit(stale ? 1 : 0);
