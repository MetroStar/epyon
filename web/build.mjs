// Builds web/src/* into the committed bundle web/static/{app.js,app.css}.
//   npm run build   write the bundle
//   npm run check   fail if the committed bundle is stale (used by CI)
//
// app.js = the ES-module bundle (src/index.js, wrapped in an IIFE that also puts
// its exports on `window`). The UI still uses inline `onclick="fn()"` handlers,
// which need global functions, hence the window assignment in src/index.js.
import { build, transform } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes("--check");
const common = { charset: "utf8", target: "es2020", legalComments: "inline" };
const banner = src => `/* GENERATED by web/build.mjs from ${src} - do not edit. */\n`;

const modules = await build({
  ...common,
  entryPoints: [join(root, "src/index.js")],
  bundle: true,
  format: "iife",
  write: false,
});
const css = await transform(readFileSync(join(root, "src/main.css"), "utf8"), { ...common, loader: "css" });

const outputs = {
  "static/app.js": banner("web/src/index.js") + modules.outputFiles[0].text,
  "static/app.css": banner("web/src/main.css") + css.code,
};

let stale = false;
for (const [out, text] of Object.entries(outputs)) {
  const path = join(root, out);
  if (check) {
    let current = "";
    try { current = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (current !== text) { console.error(`${out} is stale; run: cd web && npm run build`); stale = true; }
  } else {
    writeFileSync(path, text);
    console.log(`built ${out} (${text.length} bytes)`);
  }
}
process.exit(stale ? 1 : 0);
